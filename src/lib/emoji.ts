const RECENTS_KEY = 'wt_chat_emoji_recents'
const RECENTS_MAX = 24

/** Emoji used recently, most recent first. */
export function readEmojiRecents(): EmojiItem[] {
  const raw = storage.getItem(RECENTS_KEY)
  if (!raw) return []
  try {
    const chars = JSON.parse(raw) as unknown
    if (!Array.isArray(chars)) return []
    return chars.filter((c): c is string => typeof c === 'string').map((c) => BY_CHAR.get(c)).filter((e): e is EmojiItem => Boolean(e))
  } catch {
    return []
  }
}

/** Remember that an emoji was just used, so it floats to the top next time. */
export function rememberEmoji(char: string): EmojiItem[] {
  if (!BY_CHAR.has(char)) return readEmojiRecents()
  const next = [char, ...readEmojiRecents().map((e) => e.char).filter((c) => c !== char)].slice(0, RECENTS_MAX)
  storage.setItem(RECENTS_KEY, JSON.stringify(next))
  return next.map((c) => BY_CHAR.get(c)!).filter(Boolean)
}
