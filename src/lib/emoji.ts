export const EMOJI_GROUPS: EmojiGroup[] = (() => {
  // Each emoji is offered once, in the first group that claims it, and entries
  // whose glyph failed to survive an edit are dropped rather than rendered as a
  // stray word.
  const seen = new Set<string>()
  return RAW.map((g) => ({
    id: g.id,
    label: g.label,
    icon: g.icon,
    items: g.items.map(parse).filter((item) => {
      if (!/\p{Extended_Pictographic}/u.test(item.char)) return false
      if (seen.has(item.char)) return false
      seen.add(item.char)
      return true
    }),
  }))
})()

/** Flat, de-duplicated view — used by search. */
export const ALL_EMOJI: EmojiItem[] = (() => {
  const seen = new Set<string>()
  const out: EmojiItem[] = []
  for (const group of EMOJI_GROUPS) {
    for (const item of group.items) {
      if (seen.has(item.char)) continue
      seen.add(item.char)
      out.push(item)
    }
  }
  return out
})()

const BY_CHAR = new Map(ALL_EMOJI.map((e) => [e.char, e]))

/** Emoji/keywords a user typed matches (name, keywords or the glyph itself). */
export function searchEmoji(query: string, limit = 96): EmojiItem[] {
  const q = query.trim().toLowerCase()
  if (!q) return []
  const exact: EmojiItem[] = []
  const starts: EmojiItem[] = []
  const partial: EmojiItem[] = []
  for (const item of ALL_EMOJI) {
    const name = item.name.toLowerCase()
    if (name === q || item.char === q) exact.push(item)
    else if (name.startsWith(q) || item.keywords.includes(q)) starts.push(item)
    else if (item.keywords.includes(q) || name.includes(q)) partial.push(item)
    if (exact.length + starts.length + partial.length >= limit) break
  }
  return [...exact, ...starts, ...partial].slice(0, limit)
}

/** Lookup for rendering: the name behind a glyph, when the catalogue knows it. */
export function emojiName(char: string): string | undefined {
  return BY_CHAR.get(char)?.name
}

