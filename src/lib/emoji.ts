/**
 * The emoji set offered in the team chat composer.
 *
 * A curated catalogue rather than the full Unicode dump: it stays small enough
 * to search instantly on a phone, and it leans towards what a crew actually
 * types to a manager (time, money, tools, yes/no, thanks). Emojis are inserted
 * as plain text, so nothing here is stored anywhere but the message body.
 */
export interface EmojiItem {
  char: string
  name: string
  keywords: string
}

export interface EmojiGroup {
  id: string
  label: string
  icon: string
  items: EmojiItem[]
}

/** `"😀 grinning face|happy|smile"` — compact so the list stays readable. */
function parse(entry: string): EmojiItem {
  const [left, ...keywordParts] = entry.split('|')
  const [char, ...nameWords] = left.trim().split(' ')
  return {
    char,
    name: nameWords.join(' '),
    keywords: `${keywordParts.join(' ')} ${nameWords.join(' ')}`.trim().toLowerCase(),
  }
}

